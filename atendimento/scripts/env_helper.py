"""
Helper para ler e atualizar o .env de forma segura.
Usado por todos os scripts de setup para propagar IDs/ARNs entre etapas.
"""
import os

ENV_FILE = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), '.env')


def load_env():
    """Carrega o .env como dict (sem alterar os.environ)."""
    env = {}
    if os.path.exists(ENV_FILE):
        with open(ENV_FILE, 'r') as f:
            for line in f:
                line = line.strip()
                if line.startswith('export ') and '=' in line:
                    key, val = line.replace('export ', '', 1).split('=', 1)
                    env[key] = val
    return env


def save_env(env):
    """Salva o dict como .env, mantendo a ordem e categorias."""
    sections = {
        'AWS Credentials': ['AWS_ACCESS_KEY_ID', 'AWS_SECRET_ACCESS_KEY', 'AWS_SESSION_TOKEN'],
        'AWS Account': ['AWS_ACCOUNT_ID', 'AWS_REGION'],
        'Amazon Connect': ['CONNECT_INSTANCE_ID', 'CONNECT_INSTANCE_URL', 'CONNECT_FLOW_ID', 'CONNECT_QUEUE_ARN'],
        'Bedrock AgentCore': ['HARNESS_EXEC_ROLE_ARN', 'HARNESS_MEMORY_ARN', 'HARNESS_871F8_ARN', 'HARNESS_VENDAS_ARN', 'HARNESS_ALUNOS_ARN', 'HARNESS_SAUDE_ARN'],
        'Cognito': ['COGNITO_POOL_ID', 'COGNITO_CLIENT_ID', 'COGNITO_USERNAME', 'COGNITO_PASSWORD'],
        'WhatsApp': ['WABA_ID', 'WHATSAPP_PHONE_NUMBER_ID', 'WHATSAPP_SOURCE_PHONE_ARN'],
        'Gateway MCP': ['GATEWAY_ROLE_ARN', 'GATEWAY_ID', 'GATEWAY_ARN'],
        'QConnect': ['ASSISTANT_ID', 'LEX_BOT_ARN'],
        'Lambda': ['BOTO3_LAYER_ARN'],
    }

    written_keys = set()
    with open(ENV_FILE, 'w') as f:
        f.write('# Auto-generated by setup scripts\n')
        for section, keys in sections.items():
            section_keys = [k for k in keys if k in env]
            if section_keys:
                f.write(f'\n# {section}\n')
                for key in section_keys:
                    f.write(f'export {key}={env[key]}\n')
                    written_keys.add(key)

        # Write any remaining keys not in sections
        remaining = {k: v for k, v in env.items() if k not in written_keys}
        if remaining:
            f.write('\n# Other\n')
            for key, val in remaining.items():
                f.write(f'export {key}={val}\n')


def set_env(key, value):
    """Atualiza uma variavel no .env e no os.environ."""
    env = load_env()
    env[key] = str(value)
    save_env(env)
    os.environ[key] = str(value)
    print(f'  .env: {key}={str(value)[:80]}')


def get_env(key, default=None):
    """Le uma variavel do os.environ ou do .env."""
    val = os.environ.get(key)
    if val:
        return val
    env = load_env()
    return env.get(key, default)


def require_env(key):
    """Le uma variavel obrigatoria. Falha se nao existir."""
    val = get_env(key)
    if not val:
        print(f'ERRO: {key} nao definido. Execute setup.py --discover primeiro.')
        raise SystemExit(1)
    return val
